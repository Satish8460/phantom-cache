// Provenance model for telemetry schema v2 (docs/research/telemetry_schema_v2.md).
// Pure functions only: no DOM, no React, no clock. Used by components and by node:test.
// Display words (owner vocabulary, 2026-10-30): the payload class "measured" is shown as REAL and "inferred" as DERIVED with the
// qualifier "inferred". The class names themselves (payload, data-provenance, CSS) are unchanged.

export const PROVENANCE = Object.freeze({
  measured: { label: 'Real', meaning: 'Real: a direct counter or clock reading at a collection point (class name in the payload: measured).' },
  derived: { label: 'Derived', meaning: 'Computed server-side from measured values over a stated window.' },
  simulated: { label: 'Simulated', meaning: 'Generated by a synthetic model. Never live telemetry.' },
  inferred: { label: 'Derived (inferred)', meaning: 'Derived, inferred: deduced from indirect evidence; not directly observed.' },
  unavailable: { label: 'Unavailable', meaning: 'Cannot be provided in the current state; no value exists.' },
});

export const PROVENANCE_ORDER = Object.freeze(['measured', 'derived', 'inferred', 'simulated', 'unavailable']);

export function isKnownSrc(src) {
  return typeof src === 'string' && Object.prototype.hasOwnProperty.call(PROVENANCE, src);
}

function isObject(x) {
  return x !== null && typeof x === 'object' && !Array.isArray(x);
}

/**
 * Normalise one schema-v2 field `{src, v, unit, reason}` into a render-safe shape.
 * status:
 *   value        - a trustworthy number to display
 *   unavailable  - the server said so (no value)
 *   missing      - field absent from the payload (treated as unavailable, never zero)
 *   rejected     - the field violates the contract; the value is NOT shown
 */
export function readField(field, { mode = 'live' } = {}) {
  if (!isObject(field)) {
    return { status: 'missing', src: 'unavailable', reason: 'not_in_payload', unit: undefined };
  }
  const unit = typeof field.unit === 'string' ? field.unit : undefined;
  if (!isKnownSrc(field.src)) {
    return { status: 'rejected', src: 'unavailable', reason: 'unknown_provenance', unit };
  }
  if (field.src === 'unavailable') {
    if (Object.prototype.hasOwnProperty.call(field, 'v')) {
      return { status: 'rejected', src: 'unavailable', reason: 'unavailable_with_value', unit };
    }
    const reason = typeof field.reason === 'string' && field.reason ? field.reason : 'unspecified';
    return { status: 'unavailable', src: 'unavailable', reason, unit };
  }
  if (field.src === 'simulated' && mode === 'live') {
    return { status: 'rejected', src: 'unavailable', reason: 'simulated_in_live', unit };
  }
  if (!Object.prototype.hasOwnProperty.call(field, 'v')) {
    return { status: 'rejected', src: 'unavailable', reason: 'missing_value', unit };
  }
  // Numbers (finite) and booleans (flags such as an enforcing gate) are the only value types in schema 2.
  const okType = typeof field.v === 'boolean' || (typeof field.v === 'number' && Number.isFinite(field.v));
  if (!okType) {
    return { status: 'rejected', src: 'unavailable', reason: 'non_numeric_value', unit };
  }
  return { status: 'value', src: field.src, v: field.v, unit };
}

/** Build a field for one member of an object that carries a single `src` (e.g. latency_ms.p99). */
export function subField(parent, key) {
  if (!isObject(parent)) return undefined;
  // An unavailable (or unrecognised) parent is passed through whole, so a stray `v` is still rejected downstream.
  if (parent.src === 'unavailable' || !isKnownSrc(parent.src)) return { ...parent };
  if (!Object.prototype.hasOwnProperty.call(parent, key)) {
    return { src: 'unavailable', reason: 'not_in_payload', unit: parent.unit };
  }
  return { src: parent.src, v: parent[key], unit: parent.unit };
}

const REASON_TEXT = Object.freeze({
  not_implemented: 'Not implemented by the gateway yet',
  unsupported_platform: 'Not supported on the gateway platform',
  insufficient_window: 'Not enough samples in the window yet',
  telemetry_disabled: 'Telemetry is disabled on the gateway',
  no_samples: 'No samples recorded yet',
  origin_not_configured: 'No origin URL configured',
  cache_unavailable: 'Cache is not initialised',
  not_measured: 'Not measured by the gateway',
  proc_statm_read_error: 'Process memory could not be read',
  not_in_payload: 'Not reported by the gateway',
  unspecified: 'No reason given',
  unknown_provenance: 'Rejected: unrecognised provenance class',
  unavailable_with_value: 'Rejected: unavailable field carried a value',
  simulated_in_live: 'Rejected: simulated value in live mode',
  missing_value: 'Rejected: value missing',
  non_numeric_value: 'Rejected: value is not a finite number or boolean',
});

export function reasonText(code) {
  if (typeof code !== 'string' || !code) return REASON_TEXT.unspecified;
  return REASON_TEXT[code] || `Reason code: ${code}`;
}

/** Flatten every leaf that looks like a provenance field, for the "additional fields" listing. */
export function flattenProvenanceFields(node, path = [], out = [], depth = 0) {
  if (depth > 6 || !isObject(node)) return out;
  if (typeof node.src === 'string') {
    out.push({ path: path.join('.'), field: node });
    return out;
  }
  for (const [k, v] of Object.entries(node)) flattenProvenanceFields(v, [...path, k], out, depth + 1);
  return out;
}
